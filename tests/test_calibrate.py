"""Calibration on synthetic markets where the truth is known.

Prices follow GBM with a known volatility and settlements are generated by
the same process, so a correct model should be well calibrated and an
uninformed market (mid = 0.5) should lose to it on Brier.
"""

import math
from typing import Any

import numpy as np
import pytest

from edgebook.research import calibrate as calib
from edgebook.research.calibrate import _taker_pnl

HOUR = 3600
T0 = 1_790_000_000 // 86_400 * 86_400
SIG = 4e-4  # per-minute log vol


def world(days: int, seed: int = 0) -> tuple[np.ndarray, np.ndarray, list[dict[str, Any]]]:
    rng = np.random.default_rng(seed)
    n = days * 1440 + 1
    close = 80_000 * np.exp(np.concatenate([[0.0], np.cumsum(rng.normal(0, SIG, n - 1))]))
    ts = T0 + 60 * np.arange(n, dtype=np.int64)
    rows: list[dict[str, Any]] = []
    for hour in range(calib.WARMUP_DAYS * 24 + 2, days * 24, 3):
        close_ts = T0 + hour * HOUR
        settle = float(close[(close_ts - T0) // 60])
        for h in (60, 15):
            spot = float(close[(close_ts - 60 * h - T0) // 60])
            for k in np.linspace(-0.006, 0.006, 5):
                strike = spot * math.exp(k)
                rows.append(
                    {
                        "close_ts": close_ts,
                        "horizon_min": h,
                        "strike_type": "greater",
                        "floor": strike,
                        "cap": None,
                        "result": "yes" if settle > strike else "no",
                        "expiration_value": settle,
                        "bid": 0.46,
                        "ask": 0.54,
                    }
                )
    return ts, close, rows


def test_true_model_beats_uninformed_market_and_is_calibrated() -> None:
    ts, close, rows = world(days=20)
    report = calib.run(ts, close, rows, thresholds=(0.02,))
    assert report.n_scored > 300
    assert report.basis_bps["median"] == pytest.approx(0.0, abs=1e-6)
    for hr in report.horizons:
        har = hr.models["har_normal"]
        assert har.brier < hr.market_brier
        used = [b for b in har.buckets if b.n >= 20]
        assert sum(b.calibrated for b in used) >= len(used) - 1
        # Against a flat 0.46/0.54 market, a correct model makes money as a taker.
        assert har.taker[0].pnl.mean > 0
    text = calib.render(report)
    assert "min before close" in text
    assert "har_t4" in text


def test_skips_are_counted() -> None:
    ts, close, rows = world(days=12)
    rows = [*rows[:3]]
    rows.append({**rows[0], "bid": None, "ask": None})
    rows.append({**rows[0], "bid": 0.98, "ask": 0.99})
    rows.append({**rows[0], "close_ts": int(ts[0]) + 3 * HOUR})  # during warmup
    rows.append({**rows[0], "close_ts": int(ts[-1]) + 10 * HOUR})  # no spot
    report = calib.run(ts, close, rows)
    assert report.skipped == {"no_quote": 1, "untradeable_quote": 1, "warmup": 1, "no_spot": 1}


def test_taker_rule() -> None:
    assert _taker_pnl(0.70, 0.48, 0.50, 1, 0.02) == pytest.approx(1 - 0.50 - 0.02)
    assert _taker_pnl(0.30, 0.50, 0.52, 0, 0.02) == pytest.approx(1 - 0.50 - 0.02)
    assert _taker_pnl(0.51, 0.49, 0.51, 1, 0.0) is None
